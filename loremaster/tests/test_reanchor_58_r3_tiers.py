class _BeforeTheHealChunk:
    """Run ``before`` once, immediately before the FIRST ``_apply`` that carries a boot-heal note."""

    def __init__(self, ledger: TaskLedger, before: Callable[[], Awaitable[Any]]) -> None:
        self._ledger, self._before, self._original = ledger, before, ledger._apply  # noqa: SLF001
        self.fired = False

    async def __call__(self, fragments: Any) -> None:
        carries_heal_note = any(
            isinstance(value, dict)
            and value.get("action") == ACTION_REANCHORED
            and value.get("actor") == HEAL_ACTOR
            for fragment in fragments
            for value in fragment.params.values()
        )
        if carries_heal_note and not self.fired:
            self.fired = True
            await self._before()
        await self._original(fragments)


async def _heal_chunk_row_moved(world: TierWorld) -> list[int]:
    head = await create(world.ledger, "the head")
    legacy = "tierhealleg".ljust(32, "0")
    straggler = "tierhealrow".ljust(32, "0")
    await raw_seed_row(world.ledger, legacy, blocked_by=[], superseded_by=head)
    await raw_seed_row(world.ledger, straggler, blocked_by=[legacy])
    await raw_relate(world.ledger, legacy, straggler)
    booted = new_ledger(world.env)
    hook = _BeforeTheHealChunk(
        booted,
        lambda: raw(
            world.ledger, f"UPDATE type::record('{TASK_TABLE}', $id) SET blocked_by = []", {"id": straggler}
        ),
    )
    world.monkeypatch.setattr(booted, "_apply", hook)
    try:
        return await _captured(world, booted.ensure_ready)
    finally:
        await booted.close()
        assert hook.fired, "the heal never composed a chunk carrying its note"


