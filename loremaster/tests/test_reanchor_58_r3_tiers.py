def _levels(caplog: pytest.LogCaptureFixture) -> list[int]:
    return [record.levelno for record in caplog.records if record.getMessage() == ROLLBACK_EVENT]


def _table() -> dict[Any, int]:
    return dict(getattr(_txn, "_ROLLBACK_LOG_TIERS"))  # a ruled, not-yet-built name (mypy-clean at HEAD)


def _typed_classes() -> dict[str, type]:
    """Every proper subclass of ``TxnDomainRejectionError`` DEFINED in the driver module — the classes the
    driver can raise for a classified domain rejection (the derived domain of the table's keys)."""
    found: dict[str, type] = {}
    pending = list(_txn.TxnDomainRejectionError.__subclasses__())
    while pending:
        cls = pending.pop()
        pending.extend(cls.__subclasses__())
        if cls.__module__ == _txn.__name__:
            found[cls.__name__] = cls
    return found


