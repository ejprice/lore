async def _captured(world: TierWorld, action: Callable[[], Awaitable[Any]]) -> list[int]:
    world.caplog.clear()
    with world.caplog.at_level(logging.DEBUG):
        await action()
    return _levels(world.caplog)


async def _claim_race_8_way(world: TierWorld) -> list[int]:
    task_id = await create(world.ledger, "contended")
    racers = [new_ledger(world.env) for _ in range(8)]

    async def _race() -> None:
        results = await asyncio.gather(*(r.claim_task(task_id, f"racer-{i}") for i, r in enumerate(racers)))
        assert sum(result.claimed for result in results) == 1

    try:
        return await _captured(world, _race)
    finally:
        for racer in racers:
            await racer.close()


async def _lost_transition(world: TierWorld) -> list[int]:
    task_id = await create(world.ledger, "raced")
