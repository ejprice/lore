LEGS = [(cls, trigger) for cls, triggers in sorted(TRIGGERS.items()) for trigger in triggers]


def _assert_levels(levels: list[int], tier: int, trigger: Trigger, where: str) -> None:
    names = [logging.getLevelName(level) for level in levels]
    if trigger.count is None:
        assert levels and all(level == tier for level in levels), (
            f"{where}: expected ≥ 1 rollback, every one at {logging.getLevelName(tier)}; got {names}"
        )
    else:
        assert levels == [tier] * trigger.count, (
            f"{where}: expected {trigger.count} × {logging.getLevelName(tier)}; got {names}"
        )


