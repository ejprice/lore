async def _keeps_unique_race(world: TierWorld) -> list[int]:
    """8 concurrent ``get_or_create_keyed`` of ONE fresh key, until a round actually conflicts (≤ 20)."""
    from _governed_contract import credentialed_app_context

    async with credentialed_app_context(
        world.monkeypatch, world.tmp_path, principals={"alice": "member"}
    ) as app:
        keep_store, email = app["ctx"]._keep_store, app["emails"]["alice"]  # noqa: SLF001
        for round_index in range(20):
            key = f"session:s-tier58r3-{round_index}"

            async def _race(key: str = key) -> None:
                outcomes = await asyncio.gather(
                    *[
                        keep_store.get_or_create_keyed(key, type="session", keeper_email=email)
                        for _ in range(8)
                    ],
                    return_exceptions=True,
                )
                raised = [outcome for outcome in outcomes if isinstance(outcome, BaseException)]
                assert not raised, raised

            levels = await _captured(world, _race)
            if levels:
                return levels
    raise AssertionError("20 rounds of an 8-way keyed mint produced no UNIQUE conflict — the leg is vacuous")


@dataclass(frozen=True)
class Trigger:
    name: str
    run: Callable[[TierWorld], Awaitable[list[int]]]
    #: ``None`` = "one or more, every one at the tier"; an int = exactly that many, every one at the tier.
    count: int | None = 1


