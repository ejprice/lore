class TestDroppingOneKeyMovesOnlyThatTier:
    """am-6 pin (iii) / am-7 §4 — GENERATED over every class: the table is the ONE source."""

    @pytest.mark.parametrize("cls", sorted(TRIGGERS))
    async def test_dropping_a_key_sends_its_trigger_to_ERROR_and_leaves_a_sibling_alone(
        self, tier_world: TierWorld, cls: str
    ) -> None:
        table = _table()
        dropped = next((key for key in table if key.__name__ == cls), None)
        assert dropped is not None, f"{cls} is not a key of the tier table"
        table.pop(dropped)
        tier_world.monkeypatch.setattr(_txn, "_ROLLBACK_LOG_TIERS", table)
        trigger = TRIGGERS[cls][0]
        levels = await trigger.run(tier_world)
        assert levels and all(level == logging.ERROR for level in levels), (
            f"with {cls} dropped from the table its trigger must fall to ERROR (deny-by-default): "
            f"{[logging.getLevelName(level) for level in levels]} — a SECOND table decides the tier"
        )
        sibling = "TxnGovernedConflictError" if cls != "TxnGovernedConflictError" else "TxnCasLostError"
        sibling_trigger = TRIGGERS[sibling][0]
        _assert_levels(
            await sibling_trigger.run(tier_world),
            RULED_TIERS[sibling],
            sibling_trigger,
            f"sibling {sibling} with {cls} dropped",
        )


