class TestTheTierTableIsKeyedByCLASSAndComplete:
    """am-7 §4 pin (i): keys are CLASSES == the driver's typed domain-rejection classes, both ways; ruled."""

    def test_the_keys_are_classes_and_equal_the_typed_domain_rejection_classes_both_ways(self) -> None:
        table = _table()
        assert all(isinstance(key, type) for key in table), (
            f"amendment 7 §4 keys the table by the CLASSIFIED CLASS, never a marker string: {list(table)}"
        )
        keyed = {key.__name__ for key in table}
        typed = set(_typed_classes())
        assert keyed == typed, (
            f"typed classes with NO tier (they would fall to ERROR unclassed): {sorted(typed - keyed)}; "
            f"tiers for classes the driver does not define: {sorted(keyed - typed)}"
        )

    def test_every_ruled_class_has_its_ruled_tier(self) -> None:
        table = {key.__name__: tier for key, tier in _table().items()}
        wrong = {
            name: logging.getLevelName(table.get(name, -1))
            for name, tier in RULED_TIERS.items()
            if table.get(name) != tier
        }
        assert not wrong, f"ruled tiers (am-7 §0 row 3) not met: {wrong}"

    def test_the_trigger_registry_covers_every_ruled_class(self) -> None:
        assert set(TRIGGERS) == set(RULED_TIERS), sorted(set(TRIGGERS) ^ set(RULED_TIERS))
        assert all(TRIGGERS.values()), "a ruled class with no trigger is an unpinned tier"


